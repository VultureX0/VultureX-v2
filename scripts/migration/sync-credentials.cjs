#!/usr/bin/env node
/* Re-sync .env.migration from the externally supplied credential file.
 * Tries every candidate source password over the IPv4 pooler and keeps the one
 * that authenticates. Prints no credentials. Read-only (SELECT 1 only).
 */
const fs = require('fs');
const postgres = require('postgres');

const EXT = 'D:/Horizon-2.0-main/Horizon-2.0-main/.env.migration.txt';
const SRC_REF = 'dvgtgrpmwkvdinlecmrj';
const DST_REF = 'beawfhpyatxhaoghbnhj';
const SRC_HOST = 'aws-0-ap-northeast-1.pooler.supabase.com';
const DST_HOST = 'aws-0-ap-southeast-2.pooler.supabase.com';

const norm = (u) => u.replace(/^postgres:\/\//, 'postgresql://');
const urlsIn = (raw) =>
  [...new Set((raw.match(/postgres(?:ql)?:\/\/[^\s"'<>)]+/g) || []).map((u) => u.replace(/[;,]+$/, '')))];
const pwFromUrl = (u) => {
  try {
    return new URL(norm(u)).password;
  } catch {
    return '';
  }
};
const refFromUrl = (u) => {
  try {
    const x = new URL(norm(u));
    return (
      x.username.split('.')[1] ||
      (x.hostname.match(/^db\.([a-z0-9]{20})\./) || [])[1] ||
      ''
    );
  } catch {
    return '';
  }
};

function collect() {
  const out = [];
  for (const f of [EXT, '.env.migration']) {
    if (!fs.existsSync(f)) continue;
    const raw = fs.readFileSync(f, 'utf8');
    for (const u of urlsIn(raw)) {
      if (u.includes(SRC_REF)) out.push({ pw: pwFromUrl(u), from: f });
    }
    for (const m of raw.matchAll(/^\s*([A-Za-z_]*PASSWORD[A-Za-z_]*)\s*=\s*(.+)$/gm)) {
      out.push({ pw: m[2].trim().replace(/^["']|["']$/g, ''), from: f + ':' + m[1] });
    }
  }
  const seen = new Set();
  return out.filter((c) => c.pw && !seen.has(c.pw) && seen.add(c.pw));
}

async function probe(pw, port) {
  const url = `postgresql://postgres.${SRC_REF}:${pw}@${SRC_HOST}:${port}/postgres`;
  const sql = postgres(url, {
    max: 1,
    ssl: 'require',
    prepare: false,
    connect_timeout: 12,
    idle_timeout: 2,
    onnotice: () => {},
  });
  try {
    const r = await sql`select current_user u, current_database() d, version() v`;
    await sql.end({ timeout: 2 });
    return { ok: true, server: r[0] };
  } catch (e) {
    await sql.end({ timeout: 2 }).catch(() => {});
    return { ok: false, error: String(e.message || e).replace(/\s+/g, ' ').slice(0, 90) };
  }
}

function destUrl() {
  const candidates = [];
  for (const f of ['.env.migration', EXT]) {
    if (!fs.existsSync(f)) continue;
    const raw = fs.readFileSync(f, 'utf8');
    for (const u of urlsIn(raw)) if (u.includes(DST_REF)) candidates.push(u);
  }
  const raw = candidates[0] || '';
  const pw = pwFromUrl(raw);
  if (!pw) return '';
  return `postgresql://postgres.${DST_REF}:${pw}@${DST_HOST}:6543/postgres`;
}

(async () => {
  const cands = collect();
  console.log('candidate source passwords:', cands.length);
  let win = null;
  for (const c of cands) {
    for (const port of [5432, 6543]) {
      const r = await probe(c.pw, port);
      console.log(`  candidate from ${c.from} @${port} -> ${r.ok ? 'OK' : r.error}`);
      if (r.ok && !win) win = { pw: c.pw, port, server: r.server, from: c.from };
      if (r.ok) break;
    }
    if (win) break;
  }
  if (!win) {
    console.log('\nNO SOURCE PASSWORD WORKS over', SRC_HOST);
    process.exit(1);
  }
  const dst = destUrl();
  if (!dst) {
    console.log('\nDestination URL missing - cannot rewrite .env.migration');
    process.exit(1);
  }
  fs.writeFileSync(
    '.env.migration',
    `# regenerated by sync-credentials.cjs - do not commit\nSOURCE_DATABASE_URL=postgresql://postgres.${SRC_REF}:${win.pw}@${SRC_HOST}:${win.port}/postgres\nDEST_DATABASE_URL=${dst}\n`
  );
  console.log('\nSOURCE CONNECTED via', SRC_HOST + ':' + win.port);
  console.log('server:', String(win.server.v).slice(0, 60), '| db:', win.server.d, '| user:', win.server.u);
  console.log('.env.migration rewritten (gitignored)');
})();
