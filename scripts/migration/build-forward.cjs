#!/usr/bin/env node
/*
 * Builds .migration/forward.sql from migrations 0002-0008.
 * Transformations (never replays destructive or data statements):
 *   CREATE TABLE            -> CREATE TABLE IF NOT EXISTS
 *   CREATE [UNIQUE] INDEX   -> ... IF NOT EXISTS
 *   ALTER TABLE ADD COLUMN  -> ADD COLUMN IF NOT EXISTS
 *   ALTER TABLE ADD CONSTRAINT -> guarded by a pg_constraint existence check
 *   CREATE POLICY           -> DROP POLICY IF EXISTS + CREATE POLICY
 *   INSERT ... SELECT       -> skipped (data adoption; source has 0 interests)
 *
 * 0000/0001 are not replayed: every table they create already exists in the
 * destination with the expected column set. 0009 (bookmarks) already exists too.
 */
const fs = require('fs');

const FILES = [
  '0002_interest_plus_messaging.sql',
  '0003_greedy_thunderbolt_ross.sql',
  '0004_business_matchmaking.sql',
  '0005_sdg_layer.sql',
  '0006_founder_profiles.sql',
  '0007_founder_roadmap.sql',
  '0008_saved_resources_reminders.sql',
];

const out = [
  '-- Forward-only schema upgrade for the company project.',
  '-- Generated by scripts/migration/build-forward.cjs. Runs inside one transaction.',
  '',
];
const skipped = [];
const counts = { createTable: 0, addColumn: 0, addConstraint: 0, index: 0, policy: 0, other: 0 };

for (const file of FILES) {
  const sql = fs.readFileSync('db/migrations/' + file, 'utf8');
  const statements = sql
    .split('--> statement-breakpoint')
    .map((s) => s.trim())
    .filter(Boolean);

  out.push(`-- ===== ${file} =====`);
  for (let stmt of statements) {
    stmt = stmt.replace(/;\s*$/, '');
    // drop pure comment-only chunks
    const withoutComments = stmt
      .split('\n')
      .filter((l) => !l.trim().startsWith('--'))
      .join('\n')
      .trim();
    if (!withoutComments) continue;

    if (/^INSERT\s+INTO/i.test(withoutComments)) {
      skipped.push(`${file}: INSERT ... SELECT`);
      continue;
    }

    if (/^CREATE\s+TABLE\s+/i.test(withoutComments)) {
      counts.createTable++;
      out.push(withoutComments.replace(/^CREATE\s+TABLE\s+(?!IF\s+NOT\s+EXISTS)/i, 'CREATE TABLE IF NOT EXISTS ') + ';');
      out.push('');
      continue;
    }

    if (/^CREATE\s+UNIQUE\s+INDEX\s+/i.test(withoutComments)) {
      counts.index++;
      out.push(withoutComments.replace(/^CREATE\s+UNIQUE\s+INDEX\s+(?!IF\s+NOT\s+EXISTS)/i, 'CREATE UNIQUE INDEX IF NOT EXISTS ') + ';');
      out.push('');
      continue;
    }

    if (/^CREATE\s+INDEX\s+/i.test(withoutComments)) {
      counts.index++;
      out.push(withoutComments.replace(/^CREATE\s+INDEX\s+(?!IF\s+NOT\s+EXISTS)/i, 'CREATE INDEX IF NOT EXISTS ') + ';');
      out.push('');
      continue;
    }

    if (/^ALTER\s+TABLE\s+.*\s+ADD\s+COLUMN\s+/i.test(withoutComments)) {
      counts.addColumn++;
      out.push(withoutComments.replace(/(ADD\s+COLUMN\s+)(?!IF\s+NOT\s+EXISTS)/i, '$1IF NOT EXISTS ') + ';');
      out.push('');
      continue;
    }

    if (/^ALTER\s+TABLE\s+.*\s+ADD\s+CONSTRAINT\s+/i.test(withoutComments)) {
      const m = withoutComments.match(/^ALTER\s+TABLE\s+"?([a-z_]+)"?\s+ADD\s+CONSTRAINT\s+"?([a-z_]+)"?\s+([\s\S]*)$/i);
      if (!m) throw new Error('cannot parse constraint: ' + withoutComments.slice(0, 100));
      const [, table, name, body] = m;
      counts.addConstraint++;
      out.push(
        `DO $vx$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '${name}' AND conrelid = 'public.${table}'::regclass) THEN ` +
          `ALTER TABLE public.${table} ADD CONSTRAINT "${name}" ${body}; END IF; END $vx$;`
      );
      out.push('');
      continue;
    }

    if (/^CREATE\s+POLICY\s+/i.test(withoutComments)) {
      const m = withoutComments.match(/^CREATE\s+POLICY\s+"?([a-z_]+)"?\s+ON\s+([a-z_."]+)/i);
      if (!m) throw new Error('cannot parse policy: ' + withoutComments.slice(0, 100));
      counts.policy++;
      out.push(`DROP POLICY IF EXISTS "${m[1]}" ON ${m[2]};`);
      out.push(withoutComments + ';');
      out.push('');
      continue;
    }

    counts.other++;
    out.push(withoutComments + ';');
    out.push('');
  }
}

fs.writeFileSync('.migration/forward.sql', out.join('\n'));
console.log('wrote .migration/forward.sql');
console.log('counts:', JSON.stringify(counts));
console.log('skipped DML:', skipped.length, skipped.join(' | ') || '(none)');
console.log('statements:', out.filter((l) => /;$/.test(l) && !l.startsWith('--')).length);
